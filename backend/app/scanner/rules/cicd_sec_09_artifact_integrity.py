"""CICD-SEC-9: Improper Artifact Integrity Validation."""
from __future__ import annotations

import re

from ..gha import job_publishes
from ..model import Rule, RuleOutcome, Status

SLSA = "https://slsa.dev/spec/v1.0/requirements"
ATTEST = "https://docs.github.com/en/actions/security-for-github-actions/using-artifact-attestations/using-artifact-attestations-to-establish-provenance-for-builds"

SBOM_RE = re.compile(r"anchore/sbom-action|\bsyft\b|cyclonedx|spdx|\bsbom\b|trivy\s+.*--format\s+(cyclonedx|spdx)|actions/attest-sbom|cdxgen|microsoft/sbom-tool", re.I)
SIGN_RE = re.compile(r"\bcosign\s+sign|sigstore/cosign-installer|sigstore/gh-action-sigstore-python|actions/attest-build-provenance|actions/attest\b|actions/attest@|"
                     r"npm\s+publish\s+[^\n]*--provenance|gpg\s+--(detach-)?sign|\bnotation\s+sign|attestations:\s*write|slsa-framework/slsa-github-generator|"
                     r"goreleaser[^\n]*sign|signs:|jarsigner|codesign|signtool", re.I)
PROVENANCE_RE = re.compile(r"slsa-framework/slsa-github-generator|actions/attest-build-provenance|provenance:\s*(true|mode=max)|npm\s+publish\s+[^\n]*--provenance|"
                           r"in-toto|witness|cosign\s+attest|actions/attest@|pypa/gh-action-pypi-publish", re.I)
VERIFY_RE = re.compile(r"cosign\s+verify|gh\s+attestation\s+verify|slsa-verifier|notation\s+verify|gpg\s+--verify|sha256sum\s+(-c|--check)|shasum\s+-a\s*256\s+(-c|--check)|"
                       r"npm\s+audit\s+signatures|sigstore\s+verify|in-toto-verify|checksum", re.I)
CONSUME_RE = re.compile(r"docker\s+pull\s+|actions/download-artifact|dawidd6/action-download-artifact|gh\s+release\s+download|(curl|wget)\s+[^\n|]*\.(tar\.gz|tgz|zip|jar|whl|deb|rpm|bin|exe)\b|oras\s+pull|helm\s+pull", re.I)


def _all_text(ctx) -> str:
    return "\n".join(w.text for w in ctx.parsed_workflows)


def _publishing(ctx) -> list[tuple[str, str, str, int]]:
    """(workflow path, job id, indicator, line) for jobs that publish artifacts."""
    out = []
    for wf in ctx.parsed_workflows:
        for job in wf.jobs:
            for ind in job_publishes(job):
                out.append((wf.path, job.id, ind, job.line))
    return out


class _ArtifactRule(Rule):
    pattern: re.Pattern
    missing_what: str = ""

    def evaluate(self, ctx):
        if not ctx.parsed_workflows:
            return RuleOutcome(Status.NOT_APPLICABLE, note="No workflows.")
        pubs = _publishing(ctx)
        if not pubs:
            return RuleOutcome(Status.NOT_APPLICABLE, note="No artifact publishing (registry push, package publish, release) detected in workflows.")
        text = _all_text(ctx)
        m = self.pattern.search(text)
        if m:
            for wf in ctx.parsed_workflows:
                ln = wf.find_line(m.group(0)[:40])
                if ln:
                    return RuleOutcome(Status.PASS, evidence=[f"{wf.path}:{ln} `{m.group(0).strip()}`"])
            return RuleOutcome(Status.PASS, evidence=[f"Indicator `{m.group(0).strip()}` found."])
        findings = []
        for path, job, ind, line in pubs[:10]:
            wf = next(w for w in ctx.parsed_workflows if w.path == path)
            findings.append(self.finding(f"Job `{job}` publishes artifacts ({ind}) but no {self.missing_what} was found in any workflow.",
                                         wf=wf, line=line, evidence_type="inferred", confidence="medium", key=f"{path}:{job}"))
        return RuleOutcome(Status.FAIL, findings, note="Absence of an indicator is not proof the control is missing (it may run outside GitHub Actions).")


class MissingSBOM(_ArtifactRule):
    id = "PT-ART-001"
    category = "CICD-SEC-9"
    title = "Missing SBOM generation for published artifacts"
    description = "Published artifacts are not accompanied by a Software Bill of Materials, so consumers cannot determine what they contain or react to new vulnerabilities."
    severity = "low"
    cwe = ["CWE-1357"]
    references = ["https://www.cisa.gov/sbom", "https://github.com/anchore/sbom-action"]
    remediation = "Generate an SBOM (syft / anchore/sbom-action / CycloneDX) in the release job and publish or attest it (`actions/attest-sbom`)."
    evidence_requirements = "Publishing indicator + absence of SBOM tooling indicators across workflows."
    false_positives = "SBOMs generated by an external release system are not visible here."
    pattern = SBOM_RE
    missing_what = "SBOM generation step"


class MissingSigning(_ArtifactRule):
    id = "PT-ART-002"
    category = "CICD-SEC-9"
    title = "Published artifacts are not signed"
    description = "Artifacts are published without a signature, so consumers cannot verify they came from this pipeline unmodified."
    severity = "medium"
    cwe = ["CWE-347", "CWE-345"]
    references = ["https://docs.sigstore.dev/cosign/signing/overview/", ATTEST]
    remediation = "Sign artifacts with Sigstore cosign (keyless via OIDC) or GitHub artifact attestations; publish npm with --provenance."
    evidence_requirements = "Publishing indicator + absence of signing indicators."
    false_positives = "Registries that sign server-side are not visible from workflow configuration."
    pattern = SIGN_RE
    missing_what = "artifact signing step"


