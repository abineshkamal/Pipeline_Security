    id = "PT-ART-003"
    category = "CICD-SEC-9"
    title = "Missing build provenance for published artifacts"
    description = "No SLSA / in-toto provenance attestation describes how and from what source the artifact was built."
    severity = "medium"
    cwe = ["CWE-345"]
    references = [SLSA, ATTEST]
    remediation = "Add `actions/attest-build-provenance` (needs `id-token: write`, `attestations: write`) or the SLSA GitHub generator to release jobs."
